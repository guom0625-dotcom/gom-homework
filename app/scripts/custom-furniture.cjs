// 직접 만든 미니룸 소품 — 디자인 캔버스("아이소메트릭 캐릭터·아이템")의 소품을
// 상자·원기둥으로 다시 만들어 Kenney 그림과 같은 카메라(45° 돌림, 45° 내려봄)·크기(px/단위)로 그린다.
// 면 색은 캔버스와 같은 3단 명암: 윗면 1, 왼쪽(+z) 0.86, 오른쪽(+x) 0.72.
// 모델 단위는 Kenney 와 같음 (나무 의자 높이 ≈ 0.47). 앞면은 -z 쪽 (기본 방향에서 왼쪽 앞에 보임).

// ---- 기본 도형: 면 = { pts: [[x,y,z]...] (바깥에서 봤을 때 반시계), n: 법선, color } ----
function box(x0, y0, z0, x1, y1, z1, color) {
    const v = (x, y, z) => [x, y, z];
    return [
        { n: [0, 1, 0], pts: [v(x0, y1, z0), v(x0, y1, z1), v(x1, y1, z1), v(x1, y1, z0)], color },
        { n: [0, -1, 0], pts: [v(x0, y0, z0), v(x1, y0, z0), v(x1, y0, z1), v(x0, y0, z1)], color },
        { n: [1, 0, 0], pts: [v(x1, y0, z0), v(x1, y1, z0), v(x1, y1, z1), v(x1, y0, z1)], color },
        { n: [-1, 0, 0], pts: [v(x0, y0, z0), v(x0, y0, z1), v(x0, y1, z1), v(x0, y1, z0)], color },
        { n: [0, 0, 1], pts: [v(x0, y0, z1), v(x1, y0, z1), v(x1, y1, z1), v(x0, y1, z1)], color },
        { n: [0, 0, -1], pts: [v(x0, y0, z0), v(x0, y1, z0), v(x1, y1, z0), v(x1, y0, z0)], color },
    ];
}

// 각뿔대 (원기둥 근사): 아래 반지름 r0, 위 반지름 r1, n 각
function frustum(cx, cz, y0, y1, r0, r1, n, color, topColor = color) {
    const ring = (y, r) => Array.from({ length: n }, (_, i) => {
        const a = (i + 0.5) * 2 * Math.PI / n;
        return [cx + r * Math.cos(a), y, cz + r * Math.sin(a)];
    });
    const lo = ring(y0, r0), hi = ring(y1, r1);
    const faces = [
        { n: [0, 1, 0], pts: [...hi].reverse(), color: topColor },
        { n: [0, -1, 0], pts: lo, color },
    ];
    for (let i = 0; i < n; i++) {
        const j = (i + 1) % n;
        const a = (i + 1) * 2 * Math.PI / n;
        faces.push({ n: [Math.cos(a), 0, Math.sin(a)], pts: [lo[i], lo[j], hi[j], hi[i]], color });
    }
    return faces;
}

// 위를 보는 납작한 다각형 (컵 속, 흙 등)
function disc(cx, cz, y, r, n, color) {
    const pts = Array.from({ length: n }, (_, i) => {
        const a = (i + 0.5) * 2 * Math.PI / n;
        return [cx + r * Math.cos(a), y, cz + r * Math.sin(a)];
    }).reverse();
    return [{ n: [0, 1, 0], pts, color }];
}

